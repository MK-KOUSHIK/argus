"""Main External LLM Integration Service for Argus (Phase 4).

Implements configurable provider adapter for frontier LLMs (OpenAI Chat Completions API)
using official HTTP API standards with:
- Zero credential exposure (keys read only from server env, never sent to frontend/logs)
- Detailed error handling (missing credentials, timeouts, rate limits, provider errors)
- Accurate token usage tracking from provider response
- Clean separation between real provider and mock testing provider
"""

from abc import ABC, abstractmethod
import time
from typing import Any, Dict, Optional
import httpx
from pydantic import BaseModel, Field

from app.core.config import settings
from app.services.pricing_service import CostBreakdown, PricingService
from app.services.tokenizer_service import TokenizerService


# ============================================================================
# Exception Hierarchy
# ============================================================================

class MainLLMError(Exception):
    """Base exception for main LLM operations."""

    def __init__(self, message: str, status_code: int = 500, error_code: str = "MAIN_LLM_ERROR"):
        super().__init__(message)
        self.message = message
        self.status_code = status_code
        self.error_code = error_code


class MissingCredentialsError(MainLLMError):
    """Raised when external API credentials are not configured."""

    def __init__(
        self,
        message: str = "Main LLM API credentials not configured. Please set OPENAI_API_KEY in your environment.",
    ):
        super().__init__(message, status_code=400, error_code="MISSING_CREDENTIALS")


class ProviderAuthenticationError(MainLLMError):
    """Raised when the provider rejects the API key or authentication."""

    def __init__(self, message: str = "External provider rejected authentication credentials"):
        super().__init__(message, status_code=401, error_code="AUTHENTICATION_FAILED")


class ProviderRateLimitError(MainLLMError):
    """Raised when the provider rate limit is exceeded."""

    def __init__(self, message: str = "Main LLM provider rate limit exceeded. Please retry later."):
        super().__init__(message, status_code=429, error_code="RATE_LIMIT_EXCEEDED")


class ProviderTimeoutError(MainLLMError):
    """Raised when external provider call times out."""

    def __init__(self, message: str = "Main LLM provider call timed out"):
        super().__init__(message, status_code=504, error_code="PROVIDER_TIMEOUT")


class ProviderAPIError(MainLLMError):
    """Raised when provider returns an unexpected HTTP or API error."""

    def __init__(self, message: str = "External provider API returned an error", status_code: int = 502):
        super().__init__(message, status_code=status_code, error_code="PROVIDER_API_ERROR")


# ============================================================================
# Domain Schemas
# ============================================================================

class ProviderStatus(BaseModel):
    """Provider connection and configuration status without exposing secrets."""

    provider: str = Field(description="Name of configured provider (e.g. openai)")
    model: str = Field(description="Active default target model")
    is_configured: bool = Field(description="True if required credentials are set in environment")
    base_url: str = Field(description="HTTP endpoint base URL")
    message: str = Field(description="Human-readable status summary")


class ProviderUsage(BaseModel):
    """Token consumption reported by the LLM provider."""

    prompt_tokens: int = Field(description="Number of tokens in the input prompt")
    completion_tokens: int = Field(description="Number of tokens generated in completion")
    total_tokens: int = Field(description="Total tokens consumed")


class ProviderResponse(BaseModel):
    """Result of external LLM execution."""

    content: str = Field(description="Generated textual answer from the LLM")
    model: str = Field(description="Model used by the provider")
    usage: ProviderUsage = Field(description="Tokens reported by provider")
    cost: CostBreakdown = Field(description="Actual cost calculated from provider token usage")
    latency_ms: int = Field(description="Duration of provider network call in milliseconds")
    finish_reason: Optional[str] = Field(default="stop", description="Completion termination reason")
    is_mock: bool = Field(default=False, description="Whether this response was generated by a mock provider")


# ============================================================================
# Provider Adapters
# ============================================================================

class BaseLLMProvider(ABC):
    """Abstract interface for external LLM providers."""

    @abstractmethod
    def is_configured(self) -> bool:
        """Check if provider credentials are set in environment."""
        pass

    @abstractmethod
    def get_status(self) -> ProviderStatus:
        """Get provider configuration status without leaking credentials."""
        pass

    @abstractmethod
    async def generate(
        self,
        prompt: str,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> ProviderResponse:
        """Generate response from frontier model."""
        pass


class OpenAIProvider(BaseLLMProvider):
    """OpenAI Chat Completions API adapter."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        base_url: Optional[str] = None,
        default_model: Optional[str] = None,
        timeout: Optional[float] = None,
    ):
        self._api_key = api_key or settings.OPENAI_API_KEY
        self._base_url = (base_url or settings.OPENAI_API_BASE).rstrip("/")
        self._default_model = default_model or settings.MAIN_LLM_MODEL
        self._timeout = timeout or settings.MAIN_LLM_TIMEOUT_SECONDS

    def is_configured(self) -> bool:
        return bool(self._api_key and self._api_key.strip())

    def get_status(self) -> ProviderStatus:
        configured = self.is_configured()
        msg = (
            f"OpenAI provider ready ({self._default_model})"
            if configured
            else "OpenAI API key not configured. Set OPENAI_API_KEY in environment to enable external execution."
        )
        return ProviderStatus(
            provider="openai",
            model=self._default_model,
            is_configured=configured,
            base_url=self._base_url,
            message=msg,
        )

    async def generate(
        self,
        prompt: str,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> ProviderResponse:
        """Dispatch prompt to OpenAI Chat Completions API."""
        if not self.is_configured():
            raise MissingCredentialsError(
                "Cannot execute prompt on OpenAI: OPENAI_API_KEY is not set. "
                "Configure OPENAI_API_KEY in your environment or .env file."
            )

        target_model = model or self._default_model
        temp = temperature if temperature is not None else settings.MAIN_LLM_TEMPERATURE
        max_tok = max_tokens if max_tokens is not None else settings.MAIN_LLM_MAX_TOKENS

        endpoint = f"{self._base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self._api_key.strip()}",
            "Content-Type": "application/json",
            "Accept": "application/json",
        }

        payload: Dict[str, Any] = {
            "model": target_model,
            "messages": [
                {"role": "user", "content": prompt},
            ],
            "temperature": temp,
            "max_tokens": max_tok,
        }

        start_time = time.perf_counter()
        try:
            async with httpx.AsyncClient(timeout=self._timeout) as client:
                response = await client.post(endpoint, json=payload, headers=headers)
        except httpx.ConnectError as exc:
            raise ProviderAPIError(
                f"Failed to connect to OpenAI endpoint at {self._base_url}: {str(exc)}",
                status_code=502,
            ) from exc
        except httpx.TimeoutException as exc:
            raise ProviderTimeoutError(
                f"OpenAI request timed out after {self._timeout}s."
            ) from exc
        except Exception as exc:
            raise ProviderAPIError(
                f"Network error communicating with OpenAI: {str(exc)}",
                status_code=500,
            ) from exc

        duration_ms = int((time.perf_counter() - start_time) * 1000)

        # Handle HTTP status codes
        if response.status_code == 401:
            raise ProviderAuthenticationError("OpenAI authentication failed: Invalid API key.")
        if response.status_code == 429:
            raise ProviderRateLimitError("OpenAI rate limit or quota exceeded.")
        if response.status_code != 200:
            err_msg = response.text
            try:
                err_json = response.json()
                if "error" in err_json and "message" in err_json["error"]:
                    err_msg = err_json["error"]["message"]
            except Exception:
                pass
            raise ProviderAPIError(
                f"OpenAI returned error HTTP {response.status_code}: {err_msg}",
                status_code=response.status_code if response.status_code >= 400 else 502,
            )

        try:
            data = response.json()
            content = data["choices"][0]["message"]["content"]
            usage_data = data.get("usage", {})
            prompt_tokens = usage_data.get("prompt_tokens", 0)
            completion_tokens = usage_data.get("completion_tokens", 0)
            total_tokens = usage_data.get("total_tokens", prompt_tokens + completion_tokens)
            finish_reason = data["choices"][0].get("finish_reason", "stop")
        except (KeyError, IndexError, ValueError) as exc:
            raise ProviderAPIError(f"Malformed response payload from OpenAI: {str(exc)}") from exc

        # Calculate actual cost from provider reported tokens
        actual_cost = PricingService.calculate_actual_cost(
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            model=target_model,
        )

        return ProviderResponse(
            content=content,
            model=target_model,
            usage=ProviderUsage(
                prompt_tokens=prompt_tokens,
                completion_tokens=completion_tokens,
                total_tokens=total_tokens,
            ),
            cost=actual_cost,
            latency_ms=duration_ms,
            finish_reason=finish_reason,
            is_mock=False,
        )


class MockLLMProvider(BaseLLMProvider):
    """Mock provider for unit/integration testing with zero paid API calls."""

    def __init__(
        self,
        canned_response: Optional[str] = None,
        prompt_tokens: int = 25,
        completion_tokens: int = 50,
        model: str = "gpt-4o",
        latency_ms: int = 45,
    ):
        self._canned_response = canned_response or "Mock external LLM answer."
        self._prompt_tokens = prompt_tokens
        self._completion_tokens = completion_tokens
        self._model = model
        self._latency_ms = latency_ms

    def is_configured(self) -> bool:
        return True

    def get_status(self) -> ProviderStatus:
        return ProviderStatus(
            provider="mock",
            model=self._model,
            is_configured=True,
            base_url="http://mock-provider.local",
            message="Mock Provider Active for Automated Testing",
        )

    async def generate(
        self,
        prompt: str,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> ProviderResponse:
        target_model = model or self._model
        # Use exact tokenizer count if available for prompt tokens
        tok_res = TokenizerService.count_tokens(prompt, target_model)
        prompt_toks = tok_res.token_count if tok_res.token_count > 0 else self._prompt_tokens
        completion_toks = self._completion_tokens

        actual_cost = PricingService.calculate_actual_cost(
            prompt_tokens=prompt_toks,
            completion_tokens=completion_toks,
            model=target_model,
        )

        return ProviderResponse(
            content=self._canned_response,
            model=target_model,
            usage=ProviderUsage(
                prompt_tokens=prompt_toks,
                completion_tokens=completion_toks,
                total_tokens=prompt_toks + completion_toks,
            ),
            cost=actual_cost,
            latency_ms=self._latency_ms,
            finish_reason="stop",
            is_mock=True,
        )


class MainLLMService:
    """Singleton service manager for main frontier LLMs."""

    _active_provider: Optional[BaseLLMProvider] = None

    @classmethod
    def get_provider(cls) -> BaseLLMProvider:
        """Get or initialize active provider."""
        if cls._active_provider is None:
            cls._active_provider = OpenAIProvider()
        return cls._active_provider

    @classmethod
    def set_provider(cls, provider: BaseLLMProvider) -> None:
        """Set or override provider (useful for testing)."""
        cls._active_provider = provider

    @classmethod
    def reset_provider(cls) -> None:
        """Reset provider to default environment-driven provider."""
        cls._active_provider = None

    @classmethod
    def check_status(cls) -> ProviderStatus:
        """Inspect provider configuration without exposing secrets."""
        provider = cls.get_provider()
        return provider.get_status()

    @classmethod
    async def generate(
        self,
        prompt: str,
        model: Optional[str] = None,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> ProviderResponse:
        """Generate response via active provider."""
        provider = self.get_provider()
        return await provider.generate(
            prompt=prompt,
            model=model,
            temperature=temperature,
            max_tokens=max_tokens,
        )
